# Reference values for test_spread.jl: the elites that QDax's MELSRepertoire keeps after a
# sequence of solutions, each evaluated several times, is added one solution at a time.
# `python3 generate_spread.py` rewrites `spread.jl` next to it. Needs qdax 0.5.0.
#
# Every solution has a single most visited cell: QDax breaks a tie by the lowest cell index
# and SpreadArchive by the cell visited first. The cells are those of the nearest centroid,
# as in a CVTArchive with the same centroids.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from qdax.core.containers.mels_repertoire import MELSRepertoire

rng = np.random.default_rng(11)
lines = ["# Generated by generate_spread.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def nearest(points, centroids):
    return np.argmin(((points[:, None, :] - centroids[None, :, :]) ** 2).sum(-1), axis=1)


lines.append("const spread_cases = [")
for num_cells, num_samples, noise, count in ((6, 5, 0.08, 80), (12, 4, 0.15, 120), (4, 1, 0.1, 40), (8, 7, 0.05, 100)):
    centroids = rng.uniform(0, 1, size=(num_cells, 2))
    fitness, descriptors = [], []
    while len(fitness) < count:
        center = rng.uniform(0, 1, size=2)
        d = np.clip(center + noise * rng.standard_normal((num_samples, 2)), 0, 1)
        cells = nearest(d, centroids)
        counts = np.bincount(cells, minlength=num_cells)
        if np.sum(counts == counts.max()) > 1:
            continue
        fitness.append(rng.uniform(-1, 1) + 0.1 * rng.standard_normal(num_samples))
        descriptors.append(d)
    fitness = np.array(fitness)
    descriptors = np.array(descriptors)
    genotypes = jnp.arange(count, dtype=jnp.float64)[:, None]
    rep = MELSRepertoire.init_default(genotypes[0], jnp.array(centroids))
    for k in range(count):
        rep = rep.add(genotypes[k:k + 1], jnp.array(descriptors[k:k + 1]), jnp.array(fitness[k:k + 1]))
    kept = np.array(rep.fitnesses).ravel()
    occupied = ~np.isinf(kept)
    ids = np.where(occupied, np.round(np.array(rep.genotypes)[:, 0]).astype(int) + 1, 0)
    lines.append(f"    (centroids={fmt(centroids)}, num_samples={num_samples},")
    lines.append(f"     fitness={fmt(fitness)},")
    lines.append(f"     descriptors={fmt(descriptors)},")
    lines.append(f"     elite={list(map(int, ids))},")
    lines.append(f"     elite_fitness={fmt(np.where(occupied, kept, 0.0))},")
    lines.append(f"     elite_spread={fmt(np.where(occupied, np.array(rep.spreads), 0.0))}),")
lines.append("]")
open("spread.jl", "w").write("\n".join(lines) + "\n")
