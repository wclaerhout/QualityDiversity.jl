# Reference values for test_stochastic.jl: the fitness and descriptor that QDax's
# `average` and `median` extractors give for fixed samples, as Sampled computes them with
# Average() and Median(). `python3 generate_sampling.py` rewrites `sampling.jl` next to it.
# Needs qdax 0.5.0. pyribs has no sampling wrapper. An odd and an even number of samples
# check both forms of the median.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from qdax.utils.sampling import average, median

rng = np.random.default_rng(4)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines = ["# Generated by generate_sampling.py; do not edit.", "const sampling_cases = ["]
for k in (5, 4):
    F = rng.normal(size=(20, k))
    D = rng.uniform(size=(20, k, 2))
    # samples one column per solution; descriptors indexed (dimension, sample, solution)
    lines.append(f"    (fitness=reshape({fmt(F)}, {k}, 20), descriptors=reshape({fmt(D)}, 2, {k}, 20),")
    lines.append(f"     average_fitness={fmt(average(jnp.asarray(F)))}, median_fitness={fmt(median(jnp.asarray(F)))},")
    lines.append(f"     average_descriptor=reshape({fmt(average(jnp.asarray(D)))}, 2, 20),")
    lines.append(f"     median_descriptor=reshape({fmt(median(jnp.asarray(D)))}, 2, 20)),")
lines.append("]")

with open(__file__.replace("generate_sampling.py", "sampling.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
