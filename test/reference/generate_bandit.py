# Reference values for test_bandit.jl: the emitters that pyribs's BanditScheduler runs in
# each round, with stand-in emitters and an archive whose statuses are drawn at random.
# `python3 generate_bandit.py` rewrites `bandit.jl` next to it. Needs ribs 0.12.0; QDax
# has no bandit scheduler.
#
# The scheduler of this package takes the log of the total selections in UCB1, as Algorithm
# 1 of Cully (2021), and pyribs that of the total successes; in these sequences that never
# changes a choice. When emitters tie for a slot, which happens between emitters that
# never ran and between emitters with the same counts, this package takes the first in
# the pool and pyribs the last (for pools of up to 16, where numpy's sort is stable). An
# emitter that restarts does so after the tell of a round.
import numpy as np
from ribs.schedulers import BanditScheduler


class Archive:
    measure_dim, solution_dim, empty = 2, 1, False

    def add(self, solution, objective, measures, **_):
        return {"status": self.statuses}


class Emitter:
    def __init__(self, n):
        self.batch_size, self.solution_dim = n, 1

    def ask(self):
        return np.zeros((self.batch_size, 1))

    def tell(self, *args, **kwargs):
        pass


class RestartingEmitter(Emitter):
    def __init__(self, n):
        super().__init__(n)
        self.restarts = 0


def jl(x):
    return "[" + ", ".join(jl(v) for v in x) + "]" if isinstance(x, (list, tuple)) else str(int(x))


rng = np.random.default_rng(1)
lines = ["# Generated by generate_bandit.py; do not edit.", "const bandit_cases = ["]
for sizes, restarting, num_active, reselect, rounds, accept in (
        ((2, 2, 2, 2), (0, 0, 0, 0), 2, "terminated", 40, (0.3, 0.6, 0.2, 0.5)),
        ((3, 5, 2), (1, 0, 1), 1, "terminated", 40, (0.5, 0.2, 0.7)),
        ((4, 4, 4, 4, 4), (1, 1, 1, 0, 0), 3, "terminated", 50, (0.4, 0.4, 0.6, 0.3, 0.5)),
        ((2, 3, 4), (0, 1, 0), 2, "all", 40, (0.2, 0.5, 0.8)),
        ((5, 5, 5, 5, 5, 5), (1, 1, 1, 1, 1, 1), 2, "terminated", 60, (0.1, 0.3, 0.5, 0.7, 0.2, 0.4))):
    pool = [RestartingEmitter(n) if r else Emitter(n) for n, r in zip(sizes, restarting)]
    archive = Archive()
    scheduler = BanditScheduler(archive, pool, num_active=num_active, reselect=reselect)
    actives, statuses, restarts = [], [], []
    for _ in range(rounds):
        scheduler.ask()
        active = [i for i, a in enumerate(scheduler.active) if a]
        # 0 rejected, 1 improved, 2 new cell
        st = np.concatenate([(rng.random(sizes[i]) < accept[i]) * rng.integers(1, 3, sizes[i]) for i in active])
        archive.statuses = st.astype(np.int32)
        scheduler.tell(np.zeros(len(st)), np.zeros((len(st), 2)))
        restarted = [i for i in active if restarting[i] and rng.random() < 0.2]
        for i in restarted:
            pool[i].restarts += 1
        actives.append([i + 1 for i in active])
        statuses.append(list(st))
        restarts.append([i + 1 for i in restarted])
    lines.append(f"    (sizes={jl(sizes)}, restarting={jl(restarting)}, num_active={num_active}, "
                 f"reselect={'QD.ReselectAll()' if reselect == 'all' else 'QD.ReselectTerminated()'},")
    lines.append("     actives=Vector{Int}[" + ", ".join(jl(a) for a in actives) + "],")
    lines.append("     statuses=Vector{Int}[" + ", ".join(jl(s) for s in statuses) + "],")
    lines.append("     restarts=Vector{Int}[" + ", ".join(jl(r) for r in restarts) + "]),")
lines.append("]")

with open(__file__.replace("generate_bandit.py", "bandit.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
