# Reference values for test_pareto.jl: the solutions that MOME-PGX keeps in one cell, whose
# front is full more often than not, after a sequence of insertions. MOME-PGX removes the
# solution with the smallest crowding distance from a full front, as ReplaceCrowded does.
# `python3 generate_crowding.py <MOME_PGX>` rewrites `crowding.jl` next to it, with
# <MOME_PGX> a clone of github.com/adaptive-intelligent-robotics/MOME_PGX (commit 58c34b7),
# with the packages of requirements.txt. The repository was written for jax 0.3, so two
# names that later versions removed are restored first, with their old meaning.
import sys
import numpy as np

sys.path.insert(0, sys.argv[1])
import jax
import jax.numpy as jnp

if not hasattr(jax.random, "KeyArray"):
    jax.random.KeyArray = jax.Array
if not hasattr(jnp, "row_stack"):
    jnp.row_stack = jnp.vstack
from qdax.core.containers.biased_sampling_mome_repertoire import BiasedSamplingMOMERepertoire

rng = np.random.default_rng(7)
lines = ["# Generated by generate_crowding.py; do not edit."]

def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"

# Inserts the rows of `fits` one at a time into an empty front of length L and returns the
# ids (row numbers from 0) of the solutions that remain.
def pgx_front(fits, L):
    m = fits.shape[1]
    front = jnp.zeros((L, m), dtype=jnp.float32)
    ids = jnp.zeros((L, 1))
    descriptors = jnp.zeros((L, 1))
    mask = jnp.ones(L, dtype=bool)
    for i, f in enumerate(fits):
        front, ids, descriptors, mask, _, _ = BiasedSamplingMOMERepertoire._update_masked_pareto_front(
            None, front, ids, descriptors, mask, jnp.array(f[None, :]), jnp.array([[float(i)]]),
            jnp.zeros((1, 1)), jnp.zeros(1, dtype=bool))
    return sorted(int(round(i)) for i in np.array(ids)[~np.array(mask), 0])

t = rng.uniform(0, 1, size=40)
anti = np.stack([t, 1 - t], axis=1)
mixed = rng.uniform(0, 1, size=(60, 2))
s = rng.uniform(0, 1, size=(60, 3))
sphere = s / np.linalg.norm(s, axis=1, keepdims=True)    # all on one front
three = rng.uniform(0, 1, size=(60, 3))
lines.append("const crowding_cases = [")
# Fronts of at least 2M solutions, so that the ends of the objectives, whose distance is
# infinite, never fill a front and a removal is never a tie.
for name, pts, sizes in (("anti", anti, (4, 10)), ("mixed", mixed, (4, 6)),
                         ("sphere", sphere, (7, 15)), ("three", three, (7, 10))):
    pts = np.float32(pts)
    for L in sizes:
        kept = pgx_front(pts, L)
        lines.append(f'    (name="{name}", max_front={L}, fitness={fmt(pts)}, objectives={pts.shape[1]}, kept={kept}),')
lines.append("]")
open("crowding.jl", "w").write("\n".join(lines) + "\n")
