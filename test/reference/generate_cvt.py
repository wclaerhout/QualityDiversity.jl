# Reference values for test_cvt.jl: the cell that pyribs's CVTArchive and QDax's
# get_cells_indices give a descriptor for fixed centroids. `python3 generate_cvt.py`
# rewrites `cvt.jl` next to it. Needs ribs 0.12.0 and qdax 0.5.0.
#
# Some descriptors lie outside the unit box: pyribs clips them to the box before it
# looks up the nearest centroid, and QDax does not clip. The descriptors are drawn from a
# continuous distribution, so no descriptor is equally near two centroids.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from ribs.archives import CVTArchive
from qdax.core.containers.mapelites_repertoire import get_cells_indices

rng = np.random.default_rng(2027)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def ints(a):
    return "[" + ", ".join(str(int(v)) for v in np.ravel(a)) + "]"


centroids = rng.uniform(0, 1, (50, 3))
descriptors = rng.uniform(-0.1, 1.1, (500, 3))
archive = CVTArchive(solution_dim=1, centroids=centroids, ranges=[(0, 1)] * 3)
pyribs = archive.index_of(np.clip(descriptors, 0, 1))
qdax = np.asarray(get_cells_indices(jnp.asarray(descriptors), jnp.asarray(centroids)))

lines = ["# Generated by generate_cvt.py; do not edit."]
# centroids and descriptors one per column; cells zero-based
lines.append(f"const cvt_case = (centroids=reshape({fmt(centroids)}, 3, :),")
lines.append(f"    descriptors=reshape({fmt(descriptors)}, 3, :),")
lines.append(f"    pyribs={ints(pyribs)},")
lines.append(f"    qdax={ints(qdax)})")

with open(__file__.replace("generate_cvt.py", "cvt.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
