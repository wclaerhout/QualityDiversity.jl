# Reference values for test_variation.jl. `python3 generate_variation.py` rewrites
# `variation.jl` next to it. Needs pymoo 0.6.2, ribs 0.12.0 and qdax 0.5.0.
#
# Polynomial mutation: pymoo's mut_pm, the form of Deb's operator in NSGA-II, run on fixed
# parents with its uniform draws scripted, so the children are exact. QDax's
# polynomial_mutation run on fixed parents, with the uniform draws it makes recovered from
# its key: it mutates exactly floor(proportion * n) entries, draws in Float32, and uses
# (x - lo) / span where Deb and pymoo use 1 - (x - lo) / span, so its children differ.
#
# Gaussian and iso+line variation: the libraries draw different random numbers, so the
# reference is the distribution of 200 000 children of fixed parents: per entry the mean,
# standard deviation and 10% and 90% quantiles, and the correlation of the first two
# entries. QDax's polynomial_crossover: the fraction of entries taken from the second
# parent, which is below the proportion because it draws the positions with replacement.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from pymoo.operators.mutation.pm import mut_pm
from ribs.emitters.operators import GaussianOperator, IsoLineOperator
from qdax.core.emitters.mutation_operators import (_polynomial_mutation, polynomial_crossover,
                                                   isoline_variation)

rng = np.random.default_rng(2030)
lines = ["# Generated by generate_variation.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


class Scripted:
    """Stands in for pymoo's generator: zeros for its choice of the entries to mutate
    (with probability 1 every entry mutates), then the scripted uniform draws."""

    def __init__(self, u):
        self.u, self.calls = u, 0

    def random(self, shape):
        self.calls += 1
        return np.zeros(shape) if self.calls == 1 else self.u.reshape(shape)


n = 150
lower = rng.uniform(-3, 0, n)
upper = lower + rng.uniform(0.5, 4, n)
x = lower + rng.uniform(0, 1, n) * (upper - lower)
u = rng.uniform(0, 1, n)
lines.append("const pymoo_polynomial_cases = [")
for eta in (20.0, 3.0):
    y = mut_pm(x[None, :], lower, upper, np.array([eta]), np.array([1.0]), False, random_state=Scripted(u))[0]
    lines.append(f"    (eta={eta}, x={fmt(x)}, lower={fmt(lower)}, upper={fmt(upper)}, u={fmt(u)}, child={fmt(y)}),")
lines.append("]")

m = 150
xq = rng.uniform(-2, 3, m)
key = jax.random.PRNGKey(11)
yq = np.asarray(_polynomial_mutation(jnp.asarray(xq), key, 1.0, 20.0, -2.0, 3.0))
key, sub = jax.random.split(key)
positions = np.asarray(jax.random.choice(sub, jnp.arange(m), shape=(m,), replace=False))
key, sub = jax.random.split(key)
drawn = np.asarray(jax.random.uniform(sub, shape=(m,), minval=0, maxval=1, dtype=jnp.float32)).astype(float)
uq = np.empty(m)
uq[positions] = drawn
lines.append(f"const qdax_polynomial_case = (eta=20.0, lower=-2.0, upper=3.0, x={fmt(xq)}, u={fmt(uq)}, child={fmt(yq)})")

N = 200_000
p1 = np.array([0.3, -1.2, 2.0, 0.0])
p2 = np.array([1.0, 0.5, -1.0, 0.0])
gaussian = GaussianOperator(sigma=0.1, seed=1).ask(np.tile(p1, (N, 1)))
iso = IsoLineOperator(iso_sigma=0.05, line_sigma=0.3, seed=2).ask(np.stack([np.tile(p1, (N, 1)), np.tile(p2, (N, 1))]))
qdax_iso = np.asarray(isoline_variation(jnp.tile(p1, (N, 1)), jnp.tile(p2, (N, 1)), jax.random.PRNGKey(3), 0.05, 0.3))
lines.append(f"const variation_parents = ({fmt(p1)}, {fmt(p2)})")
lines.append("const variation_statistics = (")
for name, a in (("pyribs_gaussian", gaussian), ("pyribs_isoline", iso), ("qdax_isoline", qdax_iso)):
    lines.append(f"    {name}=(mean={fmt(a.mean(0))}, std={fmt(a.std(0))}, q10={fmt(np.quantile(a, 0.1, axis=0))}, "
                 f"q90={fmt(np.quantile(a, 0.9, axis=0))}, cor12={float(np.corrcoef(a[:, 0], a[:, 1])[0, 1])!r}),")
lines.append(")")

children = np.asarray(polynomial_crossover(jnp.zeros((N, 10)), jnp.ones((N, 10)), jax.random.PRNGKey(4), 0.5))
lines.append(f"const qdax_crossover_fraction = {float(children.mean())!r}   # proportion 0.5, 10 entries")

with open(__file__.replace("generate_variation.py", "variation.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
