# Reference values for test_dns.jl: the solutions that QDax's DominatedNoveltyRepertoire
# and pyribs's DNSArchive keep after each batch of a sequence. `python3 generate_dns.py`
# rewrites `dns.jl` next to it. Needs qdax at commit 46b8fee (DNS is not in qdax 0.5.0)
# and ribs 0.12.0: the packages of requirements.txt, with qdax replaced by
# `pip install "qdax @ git+https://github.com/adaptive-intelligent-robotics/QDax.git@46b8fee"`.
#
# Every solution carries its number as its genotype, so a population is the set of numbers
# it keeps. The descriptors are drawn from a continuous distribution, so no two dominated
# novelty scores tie and the tie rules of the libraries do not matter. Integer fitness
# values make many solutions equally fit.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from qdax.core.containers.dns_repertoire import DominatedNoveltyRepertoire
from ribs.archives import DNSArchive

rng = np.random.default_rng(5)
lines = ["# Generated by generate_dns.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines.append("const dns_cases = [")
for capacity, k, batch, batches, integer in ((20, 3, 8, 6, False), (15, 1, 10, 5, True),
                                             (12, 5, 6, 8, False), (30, 4, 25, 4, True)):
    total = batch * batches
    descriptors = rng.normal(size=(total, 2))
    fitness = rng.integers(0, 4, size=total).astype(float) if integer else rng.normal(size=total)

    qdax = DominatedNoveltyRepertoire.init_default(
        genotype=jnp.zeros(1), descriptor_dim=2, population_size=capacity, k=k)
    ribs = DNSArchive(solution_dim=1, measure_dim=2, capacity=capacity, k_neighbors=k)
    kept = []
    for b in range(batches):
        part = slice(b * batch, (b + 1) * batch)
        ids = np.arange(b * batch, (b + 1) * batch, dtype=float)[:, None]
        qdax = qdax.add(jnp.asarray(ids), jnp.asarray(descriptors[part]), jnp.asarray(fitness[part]))
        ribs.add(ids, fitness[part], descriptors[part])
        valid = np.asarray(qdax.fitnesses[:, 0]) != -np.inf
        from_qdax = sorted(int(i) for i in np.asarray(qdax.genotypes[valid, 0]))
        from_ribs = sorted(int(i) for i in ribs.data("solution")[:, 0])
        assert from_qdax == from_ribs, (capacity, k, b, from_qdax, from_ribs)
        kept.append(from_qdax)

    lines.append(f"    (capacity={capacity}, k={k}, batch={batch},")
    lines.append(f"     fitness={fmt(fitness)},")
    lines.append(f"     descriptors={fmt(descriptors)},")
    lines.append("     kept=[" + ", ".join("[" + ", ".join(str(i + 1) for i in ids) + "]" for ids in kept) + "]),")
lines.append("]")

with open(__file__.replace("generate_dns.py", "dns.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
