# Reference values for test_cma_emitter.jl: the rounds of pyribs's
# EvolutionStrategyEmitter for each ranker, selection rule and restart rule, with the
# candidates of every round fixed in advance. `python3 generate_cma_emitter.py` rewrites
# `cma_emitter.jl` next to it. Needs ribs 0.12.0.
#
# The evolution strategy is replaced by one that returns the scripted candidates and
# records the ranking and the number of parents it is told, so the reference checks the
# statuses, the ranking, the parent count and the restarts, but not the strategy, which
# test_evolution_strategies.jl checks. The strategy never stops by itself, so a restart
# comes from the restart rule. Four rounds repeat an earlier batch, which the archive
# rejects in full, so the rule "no_improvement" fires. The directions of the random
# direction rankers are scripted too: the first search uses the first, and each restart
# the next. Two settings round the fitness to integers, so that many candidates tie.
import numpy as np
from ribs.archives import GridArchive
from ribs.emitters import EvolutionStrategyEmitter

rng = np.random.default_rng(31)
n, batch, rounds = 4, 8, 14
center = rng.normal(size=n)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def evaluate(xs, integer):
    f = -np.sum((xs - center) ** 2, axis=1)
    if integer:
        f = np.round(f)
    m = np.column_stack([2 * np.tanh(xs[:, :2].mean(1)), 2 * np.tanh(xs[:, 2:].mean(1))])
    return f, m


samples = [rng.normal(scale=1.5, size=(batch, n)) for _ in range(rounds)]
for later, earlier in ((6, 2), (10, 5), (12, 1), (13, 12)):
    samples[later] = samples[earlier].copy()
directions = [rng.normal(size=2) * 4.0 for _ in range(rounds + 1)]


class Scripted:
    def __init__(self):
        self.round = 0
        self.told = []
        self.batch_size = batch

    def ask(self):
        return samples[self.round].copy()

    def tell(self, ranking_indices, ranking_values, num_parents):
        self.told.append(([int(i) + 1 for i in ranking_indices], int(num_parents)))
        self.round += 1

    def check_stop(self, ranking_values):
        return False

    def reset(self, x0):
        pass


settings = [("2imp", "filter", "no_improvement", False), ("imp", "mu", "basic", False),
            ("obj", "filter", 3, False), ("2obj", "mu", "no_improvement", False),
            ("rd", "filter", "no_improvement", False), ("2rd", "mu", 4, False),
            ("2imp", "filter", "no_improvement", True), ("obj", "mu", "basic", True)]
lines = ["# Generated by generate_cma_emitter.py; do not edit."]
lines.append(f"const cma_emitter_center = {fmt(center)}")
# each round's candidates, one per column
lines.append("const cma_emitter_samples = [" + ",\n    ".join(f"reshape({fmt(s)}, {n}, {batch})" for s in samples) + "]")
lines.append("const cma_emitter_directions = [" + ", ".join(fmt(d) for d in directions) + "]")
lines.append("const cma_emitter_cases = [")
for ranker, selection, restart, integer in settings:
    archive = GridArchive(solution_dim=n, dims=[6, 6], ranges=[(-2, 2), (-2, 2)])
    emitter = EvolutionStrategyEmitter(archive, x0=np.zeros(n), sigma0=1.0, ranker=ranker,
                                       selection_rule=selection, restart_rule=restart,
                                       batch_size=batch, seed=1)
    scripted = Scripted()
    emitter._opt = scripted
    direction = 0
    if ranker in ("rd", "2rd"):
        emitter._ranker.target_measure_dir = directions[0]
    restarts, statuses = [], []
    for _ in range(rounds):
        xs = emitter.ask()
        f, m = evaluate(xs, integer)
        info = archive.add(xs, f, m)
        statuses.append([int(s) for s in info["status"]])
        before = emitter.restarts
        emitter.tell(xs, f, m, info)
        restarts.append(emitter.restarts)
        if emitter.restarts > before and ranker in ("rd", "2rd"):
            direction += 1
            emitter._ranker.target_measure_dir = directions[direction]
    rule = restart if isinstance(restart, int) else f'"{restart}"'
    lines.append(f'    (ranker="{ranker}", selection="{selection}", restart={rule}, integer={str(integer).lower()},')
    # per round: the ranking (one-based), the number of parents, the restarts so far, and
    # the pyribs statuses (0 rejected, 1 improved, 2 new cell)
    lines.append(f"     orders={[t[0] for t in scripted.told]},")
    lines.append(f"     parents={[t[1] for t in scripted.told]},")
    lines.append(f"     restarts={restarts},")
    lines.append(f"     statuses={statuses}),")
lines.append("]")

with open(__file__.replace("generate_cma_emitter.py", "cma_emitter.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
