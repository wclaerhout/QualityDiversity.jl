# Reference values for test_pareto.jl: hypervolumes from pymoo (HV indicator), and the
# solutions that QDax's MOMERepertoire keeps in one cell after a sequence of insertions.
# `python3 generate_pareto.py` rewrites `pareto.jl` next to it. Needs pymoo 0.6.2 and qdax 0.5.0.
import warnings
import numpy as np
import jax.numpy as jnp
from pymoo.indicators.hv import HV
from qdax.core.containers.mome_repertoire import MOMERepertoire

warnings.filterwarnings("ignore")
rng = np.random.default_rng(5)
lines = ["# Generated by generate_pareto.py; do not edit."]

def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"

# hypervolume: points are the rows of a matrix with m columns, flattened row by row
cases = []
for m, n in ((2, 6), (2, 15), (3, 5), (3, 12), (4, 6), (4, 10)):
    pts = rng.uniform(-1, 3, size=(n, m))
    cases.append((m, pts, HV(ref_point=-np.zeros(m))(-pts)))
lines.append("const hv_cases = [")
for m, pts, v in cases:
    lines.append(f"    (m={m}, points={fmt(pts)}, volume={repr(float(v))}),")
lines.append("]")

# fronts kept by QDax in a single cell, as the ids of the solutions that remain
def qdax_front(fits, L):
    n = len(fits)
    g = jnp.arange(n, dtype=jnp.float32)[:, None]
    d = jnp.full((n, 1), 0.5)
    rep = MOMERepertoire.init(g[:1], jnp.array(fits[:1], dtype=jnp.float32), d[:1], jnp.array([[0.5]]), L)
    rep = rep.add(g[1:], d[1:], jnp.array(fits[1:], dtype=jnp.float32))
    f = np.array(rep.fitnesses[0])
    ids = np.array(rep.genotypes[0])[:, 0]
    keep = ~np.any(np.isinf(f), axis=1)
    return sorted(int(round(i)) for i in ids[keep])

t = rng.permutation(30) / 30.0
anti = np.stack([t, 1 - t], axis=1)
mixed = rng.uniform(0, 1, size=(40, 2))
three = rng.uniform(0, 1, size=(40, 3))
lines.append("const front_cases = [")
for name, pts in (("anti", anti), ("mixed", mixed), ("three", three)):
    pts = np.float32(pts)
    for L in (4, 10, 50):
        kept = qdax_front([list(map(float, p)) for p in pts], L)
        lines.append(f'    (name="{name}", max_front={L}, fitness={fmt(pts)}, objectives={pts.shape[1]}, kept={kept}),')
lines.append("]")
open("pareto.jl", "w").write("\n".join(lines) + "\n")
