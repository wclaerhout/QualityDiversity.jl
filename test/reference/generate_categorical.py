# Reference values for test_categorical.jl: what pyribs's CategoricalArchive reports and
# keeps after each batch of a sequence. `python3 generate_categorical.py` rewrites
# `categorical.jl` next to it. Needs ribs 0.12.0; QDax has no categorical archive.
#
# Every solution carries its number as its genotype. Twelve cells, labeled by strings,
# receive batches of ten. The fitness values are drawn from a continuous distribution, so
# no two tie.
import numpy as np
from ribs.archives import CategoricalArchive

rng = np.random.default_rng(2028)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def ints(a):
    return "[" + ", ".join(str(int(v)) for v in np.ravel(a)) + "]"


categories = [["a", "b", "c"], ["w", "x", "y", "z"]]
batch, batches, offset = 10, 6, -5.0
total = batch * batches
fitness = rng.normal(size=total)
first = rng.integers(0, 3, total)
second = rng.integers(0, 4, total)
measures = np.array([[categories[0][i], categories[1][j]] for i, j in zip(first, second)], dtype=object)

archive = CategoricalArchive(solution_dim=1, categories=categories, qd_score_offset=offset)
statuses, values, elites, stats = [], [], [], []
for b in range(batches):
    ids = np.arange(b * batch, (b + 1) * batch)
    info = archive.add(ids[:, None] + 1.0, fitness[ids], measures[ids])
    statuses.extend(info["status"])
    values.extend(info["value"])
    elites.append(sorted(int(s) for s in archive.data("solution")[:, 0]))
    s = archive.stats
    stats.append([s.num_elites, s.coverage, s.qd_score, s.obj_max, s.obj_mean])

lines = ["# Generated by generate_categorical.py; do not edit."]
lines.append(f"const categorical_case = (categories=({categories[0]}, {categories[1]}), batch={batch}, offset={offset},")
lines.append(f"    fitness={fmt(fitness)},")
# the zero-based category of every solution in each dimension
lines.append(f"    first={ints(first)},")
lines.append(f"    second={ints(second)},")
# pyribs statuses: 0 rejected, 1 improved, 2 new cell
lines.append(f"    statuses={ints(statuses)},")
lines.append(f"    values={fmt(values)},")
lines.append(f"    elites={elites},")
# after each batch, one column: number of elites, coverage, QD score, maximum and mean fitness
lines.append(f"    stats=reshape({fmt(stats)}, 5, :))")

with open(__file__.replace("generate_categorical.py", "categorical.jl"), "w") as f:
    f.write("\n".join(lines).replace("'", '"') + "\n")
