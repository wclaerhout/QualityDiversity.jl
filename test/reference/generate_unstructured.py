# Reference values for test_unstructured.jl: what pyribs's ProximityArchive with one
# neighbor and local competition reports and keeps after each solution of a sequence,
# added one at a time. `python3 generate_unstructured.py` rewrites `unstructured.jl` next
# to it. Needs ribs 0.12.0.
#
# With k_neighbors=1 and local_competition=True, pyribs's archive follows the rule of
# UnstructuredArchive: a solution farther than the threshold from every stored one is
# new, and one within it replaces its nearest neighbor if it is fitter. pyribs grows
# without limit, so the archive of the test has room for every solution. pyribs counts a
# solution exactly at the threshold as new and UnstructuredArchive does not; the
# descriptors are drawn from a continuous distribution, so no distance equals it. pyribs
# computes a batch against the archive before it and UnstructuredArchive adds the
# solutions of a batch one at a time, so the sequence is added one solution at a time.
import numpy as np
from ribs.archives import ProximityArchive

rng = np.random.default_rng(2029)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def ints(a):
    return "[" + ", ".join(str(int(v)) for v in np.ravel(a)) + "]"


total, threshold = 150, 0.15
fitness = rng.normal(size=total)
descriptors = rng.uniform(0, 1, (total, 2))
archive = ProximityArchive(solution_dim=1, measure_dim=2, k_neighbors=1,
                           novelty_threshold=threshold, local_competition=True)
statuses, values, elites = [], [], []
for i in range(total):
    info = archive.add(np.array([[i + 1.0]]), fitness[i:i + 1], descriptors[i:i + 1])
    statuses.append(int(info["status"][0]))
    values.append(float(info["value"][0]))
    elites.append(sorted(int(s) for s in archive.data("solution")[:, 0]))

lines = ["# Generated by generate_unstructured.py; do not edit."]
lines.append(f"const unstructured_case = (threshold={threshold}, fitness={fmt(fitness)},")
# one descriptor per column
lines.append(f"    descriptors=reshape({fmt(descriptors)}, 2, :),")
# pyribs statuses: 0 rejected, 1 improved, 2 new
lines.append(f"    statuses={ints(statuses)},")
lines.append(f"    values={fmt(values)},")
# after each solution: the numbers of the stored solutions, sorted
lines.append(f"    elites={elites})")

with open(__file__.replace("generate_unstructured.py", "unstructured.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
