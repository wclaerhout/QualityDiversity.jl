# Reference values for test_evolution_strategies.jl: the batches of `strategies.jl` fed
# to pyribs's LMMAEvolutionStrategy and OpenAIEvolutionStrategy, whose own sampling is
# bypassed. `python3 generate_pyribs_strategies.py` rewrites `pyribs_strategies.jl` next
# to it; it reads `strategies.jl`, so run generate_strategies.py first. Needs ribs 0.12.0.
#
# pyribs's CMA-ES and sep-CMA-ES are not included: they differ from the update of the
# tutorial that CMAES and SepCMAES follow (see the verification page of the
# documentation).
import re
import numpy as np
from ribs.emitters.opt import LMMAEvolutionStrategy, OpenAIEvolutionStrategy

text = open(__file__.replace("generate_pyribs_strategies.py", "strategies.jl")).read()
ref = {}
for block in re.split(r"\nconst ", "\n" + text)[1:]:
    name, value = block.split(" = ", 1)
    ref[name] = eval(value)


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines = ["# Generated by generate_pyribs_strategies.py; do not edit."]

x0 = np.array(ref["lm_x0"])
n = len(x0)
es = LMMAEvolutionStrategy(sigma0=ref["lm_s0"], solution_dim=n, batch_size=6, n_vectors=3, seed=1)
es.reset(x0)
for z, y, order, parents in zip(ref["lm_Z"], ref["lm_Y"], ref["lm_orders"], ref["lm_parents"]):
    es.ask()
    es._solution_z = np.array(z).reshape(6, n)
    es._solutions = es.mean + es.sigma * np.array(y).reshape(6, n)
    es.tell(np.array(order) - 1, np.zeros(6), parents)
lines.append(f"const pyribs_lm = (mean={fmt(es.mean)}, sigma={float(es.sigma)!r}, path_sigma={fmt(es.ps)}, vectors={fmt(es.m)})")

x0 = np.array(ref["oa_x0"])
n = len(x0)
es = OpenAIEvolutionStrategy(sigma0=0.3, solution_dim=n, batch_size=8, seed=1, mirror_sampling=True,
                             lr=0.05, beta1=0.9, beta2=0.999, epsilon=1e-8, l2_coeff=0.0)
es.reset(x0)
for e, order in zip(ref["oa_E"], ref["oa_orders"]):
    es.ask()
    noise = np.array(e).reshape(4, n)
    es.noise = np.concatenate((noise, -noise))
    es._solutions = es.adam_opt.theta + 0.3 * es.noise
    es.tell(np.array(order) - 1, np.zeros(8), 4)
lines.append(f"const pyribs_openai = (theta={fmt(es.adam_opt.theta)},)")

with open(__file__.replace("generate_pyribs_strategies.py", "pyribs_strategies.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
