# Reference values for test_archives.jl: what pyribs's GridArchive and QDax's
# MapElitesRepertoire report and keep after each batch of a sequence, and the metrics of
# both. `python3 generate_grid.py` rewrites `grid.jl` next to it. Needs ribs 0.12.0 and
# qdax 0.5.0.
#
# Every solution carries its number as its genotype. Twenty cells receive batches of 16,
# so a cell often takes several solutions of one batch. Fitness and descriptors are drawn
# from continuous distributions, so no two fitness values tie and no descriptor lies
# within pyribs's tolerance of 1e-6 below a cell boundary. QDax finds the cell as the
# nearest of the grid's centroids, which is the grid cell away from such ties. pyribs
# subtracts its `qd_score_offset` from every fitness and QDax adds its `qd_offset`.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from ribs.archives import GridArchive
from qdax.core.containers.mapelites_repertoire import MapElitesRepertoire, compute_euclidean_centroids
from qdax.utils.metrics import default_qd_metrics

rng = np.random.default_rng(2026)
lines = ["# Generated by generate_grid.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def ints(a):
    return "[" + ", ".join(str(int(v)) for v in np.ravel(a)) + "]"


def kept(genotypes, fitnesses):
    return sorted(int(g) for g, f in zip(np.ravel(genotypes), np.ravel(fitnesses)) if f > -np.inf)


dims, ranges, batch, batches, offset = [5, 4], [(-1.0, 1.0), (0.0, 2.0)], 16, 8, -10.0
total = batch * batches
fitness = rng.normal(scale=3.0, size=total)
descriptors = np.column_stack([rng.uniform(-1, 1, total), rng.uniform(0, 2, total)])

archive = GridArchive(solution_dim=1, dims=dims, ranges=ranges, qd_score_offset=offset)
statuses, values, elites, stats = [], [], [], []
for b in range(batches):
    ids = np.arange(b * batch, (b + 1) * batch)
    info = archive.add(ids[:, None] + 1.0, fitness[ids], descriptors[ids])
    statuses.extend(info["status"])
    values.extend(info["value"])
    elites.append(sorted(int(s) for s in archive.data("solution")[:, 0]))
    s = archive.stats
    stats.append([s.num_elites, s.coverage, s.qd_score, s.norm_qd_score, s.obj_max, s.obj_mean])
grid_index = archive.int_to_grid_index(archive.index_of(descriptors))

centroids = compute_euclidean_centroids(grid_shape=tuple(dims), minval=[r[0] for r in ranges],
                                        maxval=[r[1] for r in ranges])
first = np.arange(batch)
repertoire = MapElitesRepertoire.init(jnp.asarray(first[:, None] + 1.0), jnp.asarray(fitness[first]),
                                      jnp.asarray(descriptors[first]), centroids)
qdax_elites, qdax_metrics = [], []
for b in range(batches):
    if b > 0:
        ids = np.arange(b * batch, (b + 1) * batch)
        repertoire = repertoire.add(jnp.asarray(ids[:, None] + 1.0), jnp.asarray(descriptors[ids]),
                                    jnp.asarray(fitness[ids]))
    qdax_elites.append(kept(repertoire.genotypes, repertoire.fitnesses))
    m = default_qd_metrics(repertoire, -offset)
    qdax_metrics.append([float(m["qd_score"]), float(m["coverage"]), float(m["max_fitness"])])

lines.append(f"const grid_case = (dims={tuple(dims)}, bounds={tuple(ranges)}, batch={batch}, offset={offset},")
lines.append(f"    fitness={fmt(fitness)},")
# one descriptor per column
lines.append(f"    descriptors=reshape({fmt(descriptors)}, 2, :),")
# pyribs statuses: 0 rejected, 1 improved, 2 new cell
lines.append(f"    statuses={ints(statuses)},")
lines.append(f"    values={fmt(values)},")
# after each batch: the numbers of the elites, sorted
lines.append(f"    elites={elites},")
lines.append(f"    qdax_elites={qdax_elites},")
# after each batch, one column: number of elites, coverage, QD score, normalized QD score,
# maximum and mean fitness (pyribs); QD score, coverage in percent, maximum fitness (QDax)
lines.append(f"    stats=reshape({fmt(stats)}, 6, :),")
lines.append(f"    qdax_metrics=reshape({fmt(qdax_metrics)}, 3, :),")
# the zero-based grid index of every descriptor, one per column
lines.append(f"    grid_index=reshape({ints(grid_index)}, 2, :))")

with open(__file__.replace("generate_grid.py", "grid.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
