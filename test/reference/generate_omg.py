# Reference values for test_gradients.jl: the children of the gradient step of OMG-MEGA in
# pyribs's GradientOperatorEmitter and QDax's OMGMEGAEmitter, with the parents and the
# coefficients known. `python3 generate_omg.py` rewrites `omg.jl` next to it. Needs ribs
# 0.12.0 and qdax 0.5.0.
#
# pyribs adds Gaussian noise of standard deviation `sigma` to every parent before the
# gradient step, which the paper and QDax do not; with sigma=0 its step is the paper's.
# Its generator is replaced by one that returns the scripted coefficients. QDax draws
# the parents and coefficients from its key; they are recovered by repeating its draws.
# Its `sigma_g` is the variance of the coefficients, so its coefficients are recorded
# already scaled. QDax normalizes a gradient by its length and pyribs by its length plus
# 1e-8.
import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
from ribs.archives import GridArchive
from ribs.emitters import GradientOperatorEmitter
from qdax.core.containers.mapelites_repertoire import MapElitesRepertoire, compute_euclidean_centroids
from qdax.core.emitters.omg_mega_emitter import OMGMEGAEmitter

rng = np.random.default_rng(8)
n, m, batch = 5, 2, 12
center = rng.normal(size=n)
A = rng.normal(size=(m, n)) * 0.4


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def evaluate(x):
    # A smooth objective and measures tanh(A x), with their Jacobian.
    f = -np.sum((x - center) ** 2) + np.sin(x[0])
    d = np.tanh(A @ x)
    J = np.zeros((1 + m, n))
    J[0] = -2 * (x - center)
    J[0, 0] += np.cos(x[0])
    J[1:] = (1 - d[:, None] ** 2) * A
    return f, d, J


population = rng.normal(size=(40, n))
evs = [evaluate(x) for x in population]
F = np.array([e[0] for e in evs])
D = np.array([e[1] for e in evs])
J = np.array([e[2] for e in evs])
Z = rng.normal(size=(batch, 1 + m))


class ScriptedNormal:
    def normal(self, loc=0.0, scale=1.0, size=None):
        if scale == 0.0:
            return np.zeros(size)
        return loc + scale * Z


archive = GridArchive(solution_dim=n, dims=[5, 5], ranges=[(-1, 1), (-1, 1)], seed=5)
archive.add(population, F, D)
emitter = GradientOperatorEmitter(archive, sigma=0.0, sigma_g=0.7, measure_gradients=True,
                                  normalize_grad=True, batch_size=batch, seed=3, x0=np.zeros(n))
emitter._rng = ScriptedNormal()
parents = emitter.ask_dqd()
pe = [evaluate(x) for x in parents]
info = archive.add(parents, [e[0] for e in pe], [e[1] for e in pe])
emitter.tell_dqd(parents, [e[0] for e in pe], [e[1] for e in pe], np.array([e[2] for e in pe]), info)
children = emitter.ask()

centroids = compute_euclidean_centroids(grid_shape=(5, 5), minval=-1.0, maxval=1.0)
repertoire = MapElitesRepertoire.init(jnp.asarray(population), jnp.asarray(F), jnp.asarray(D), centroids)
qdax = OMGMEGAEmitter(batch_size=batch, sigma_g=0.49, num_descriptors=m, centroids=centroids)
state = qdax.init(jax.random.PRNGKey(0), repertoire, jnp.asarray(population), jnp.asarray(F), jnp.asarray(D),
                  {"gradients": jnp.asarray(np.transpose(J, (0, 2, 1)))})
key = jax.random.PRNGKey(21)
qdax_children, _ = qdax.emit(repertoire, state, key)
key, sub = jax.random.split(key)
indexes = repertoire.replace(genotypes=jnp.arange(repertoire.fitnesses.shape[0])).select(
    sub, num_samples=batch, selector=qdax._selector).genotypes
coefficients = jax.random.multivariate_normal(key, shape=(batch,), mean=qdax._mu, cov=qdax._sigma)

lines = ["# Generated by generate_omg.py; do not edit."]
lines.append(f"const omg_center = {fmt(center)}")
lines.append(f"const omg_A = permutedims(reshape({fmt(A)}, {n}, {m}))")
# solutions, parents and children one per column; coefficients one column per child
lines.append(f"const omg_population = reshape({fmt(population)}, {n}, :)")
lines.append(f"const omg_pyribs = (sigma=0.7, parents=reshape({fmt(parents)}, {n}, :), "
             f"coefficients=reshape({fmt(Z)}, {1 + m}, :), children=reshape({fmt(children)}, {n}, :))")
lines.append(f"const omg_qdax = (sigma=1.0, parents=reshape({fmt(np.asarray(repertoire.genotypes)[np.asarray(indexes)])}, {n}, :), "
             f"coefficients=reshape({fmt(np.asarray(coefficients))}, {1 + m}, :), children=reshape({fmt(np.asarray(qdax_children))}, {n}, :))")

with open(__file__.replace("generate_omg.py", "omg.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
